export type MessageKey = keyof typeof messages['zh-CN']

function detectInitialLocale(): Locale {
  const saved = localStorage.getItem(STORAGE_KEY)
  if (saved === 'zh-CN' || saved === 'en-US') return saved
  return navigator.language.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en-US'
}

const currentLocale = ref<Locale>(detectInitialLocale())

export const locale = readonly(currentLocale)

export const localeLabel = computed(() => messages[currentLocale.value]['language.english'])

if (typeof document !== 'undefined') {
  document.documentElement.lang = currentLocale.value
}

export function setLocale(nextLocale: Locale) {
  currentLocale.value = nextLocale
  localStorage.setItem(STORAGE_KEY, nextLocale)
  document.documentElement.lang = nextLocale
}

export function t(key: MessageKey, params?: Record<string, unknown>): string {
  const value = messages[currentLocale.value][key] ?? messages['en-US'][key] ?? key
  return typeof value === 'function' ? value(params) : value
}

export function useI18n() {
  return {
    locale,
    localeLabel,
    setLocale,
    t,
  }
}
